/*
EXPLICACION GUIADA DE LA PLANTILLA:

1. #include <iostream>
    Esto le da al programa la capacidad de usar entradas y salidas
    Vamos a usar "cin" para entrada y "cout" para salidas
2. using namespace std;
    Esto es para no escribir std::cout y std::cin todo el tiempo. Por ahora lo usamos por simplicidad

3. int main() {...}
    main es la puerta de entrada. El programa empieza aqui. Es la funcion principal.

4. Declaracion de variables
    Son cajitas donde guardamos datos que pueden cambiar.
    
5. cout << "texto"
    Esto imprime en pantalla. Pensemos que es la salida.

6. cin >> variable
    Esto lee lo que el usuario escribe y lo guarda en la variable. Pensemos que es la entrada.
    
7. Procesamiento
    calculos con operaciones + - * /
8. return 0;
    Esto indica que el programa terminó bien.
9. endl
    Signifca que hace un salto de linea 
*/